#!/usr/bin/env python3
"""Render required, baseline, or repository workflow YAML without applying it.

The caller must verify --action-sha exists in xpossystems/ci-policy-public and review
the action at that commit. This generator validates its syntax, not its remote
existence. It never contacts GitHub or writes files.

The baseline category-tests.yml runs plan and all category suites without the
final TDD verifier, so a completed green baseline run can be cited by the full
gate without circular verification. Repository feature-tests.yml calls the
baseline at an independently verified policy commit. Public central workflows support approved repositories whose profiles
are included in this distribution. Baseline
mode executes the approved suites and regressions without the final changed-test
or evidence gates, so it can record honest TDD runs during development.

Merge queue evidence association is not implemented by this generator: the
trusted verify mode must reject merge_group until evidence for every included
PR is associated with the exact tested commit. Do not enable merge queues on
the assumption that a PR-body-only evidence verifier can validate merge groups.
"""

from __future__ import annotations

import argparse
import re


REQUIRED_HEADER = """# Generated by workflow.py; review before activation.
# merge_group verification must fail closed until per-PR evidence association exists.
name: Feature quality

"on":
  pull_request:
  merge_group:

permissions:
  contents: read

"""

BASELINE_HEADER = """# Central baseline: .github/workflows/category-tests.yml
# Public baseline workflow; only centrally approved profiles can pass.
name: Feature category tests

"on":
  workflow_call:

permissions:
  contents: read

"""

ENVIRONMENT = """env:
  QUALITY_REPOSITORY: ${{ github.repository }}
  QUALITY_HEAD_SHA: ${{ github.event.pull_request.head.sha || github.event.merge_group.head_sha || github.sha }}
  QUALITY_BASE_SHA: ${{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || '' }}
  QUALITY_PR_NUMBER: ${{ github.event.pull_request.number || '' }}
  QUALITY_EVENT_NAME: ${{ github.event_name }}

"""

PLAN_RUN_JOBS = """jobs:
  plan:
    name: Feature quality / plan
    if: ${{ true }}
    runs-on: ubuntu-latest
    timeout-minutes: 10
    outputs:
      runner: ${{ steps.plan.outputs.runner }}
      python_version: ${{ steps.plan.outputs.python_version }}
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262
        with:
          persist-credentials: false
          ref: ${{ github.sha }}
          fetch-depth: 0
      - name: Validate the feature quality contract
        id: plan
        uses: xpossystems/ci-policy-public@__ACTION_SHA__
        with:
          mode: plan
          root: ${{ github.workspace }}
          reports: ${{ runner.temp }}/quality-reports

  run:
    name: Feature quality / suites
    needs: [plan]
    runs-on: ${{ needs.plan.outputs.runner }}
    timeout-minutes: 60
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262
        with:
          persist-credentials: false
          ref: ${{ github.sha }}
          fetch-depth: 0
      - uses: actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065
        with:
          python-version: ${{ needs.plan.outputs.python_version }}
      - name: Run unit, integration, and security suites
        uses: xpossystems/ci-policy-public@__ACTION_SHA__
        with:
          mode: run
          root: ${{ github.workspace }}
          reports: ${{ runner.temp }}/quality-reports
      - name: Preserve test and security evidence
        if: ${{ always() }}
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02
        with:
          name: feature-quality-evidence
          path: ${{ runner.temp }}/quality-reports
          if-no-files-found: error
          retention-days: 14

"""

SCAN_VERIFY_JOBS = """  scan:
    name: Feature quality / security scan
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262
        with:
          persist-credentials: false
          ref: ${{ github.sha }}
          fetch-depth: 0
      - name: Prepare trusted scanner configuration
        shell: bash
        run: |
          python3 - <<'PY'
          import os
          from pathlib import Path
          root = Path(os.environ['RUNNER_TEMP']).resolve(strict=True) / 'feature-quality-trivy'
          root.mkdir(mode=0o700)
          for name, content in [('trivy.yaml', '{}\\n'), ('secret.yaml', '{}\\n'), ('ignore', '')]:
              path = root / name
              path.write_text(content)
              path.chmod(0o444)
          PY
      - name: Scan dependencies, configuration, and secrets
        uses: aquasecurity/trivy-action@ed142fd0673e97e23eac54620cfb913e5ce36c25
        env:
          TRIVY_IGNOREFILE: ${{ runner.temp }}/feature-quality-trivy/ignore
          TRIVY_SECRET_CONFIG: ${{ runner.temp }}/feature-quality-trivy/secret.yaml
          TRIVY_IGNORE_UNFIXED: 'false'
        with:
          scan-type: fs
          scan-ref: .
          scanners: vuln,misconfig,secret
          exit-code: '1'
          severity: HIGH,CRITICAL
          version: v0.70.0
          cache: 'false'
          cache-dir: ${{ runner.temp }}/feature-quality-trivy/cache
          trivy-config: ${{ runner.temp }}/feature-quality-trivy/trivy.yaml

  required:
    name: Feature quality / required
    if: ${{ always() }}
    needs: [plan, run, scan]
    runs-on: ubuntu-latest
    timeout-minutes: 10
    permissions:
      contents: read
      actions: read
      pull-requests: read
    steps:
      - name: Require every dependency to succeed
        env:
          NEEDS_JSON: ${{ toJSON(needs) }}
        shell: bash
        run: |
          python3 - <<'PY'
          import json
          import os
          results = json.loads(os.environ['NEEDS_JSON'])
          expected = {'plan', 'run', 'scan'}
          if (not isinstance(results, dict) or set(results) != expected
              or any(not isinstance(results[name], dict)
                     or results[name].get('result') != 'success'
                     for name in expected)):
              raise SystemExit('Every required job must complete successfully; missing, skipped, neutral, cancelled, or failed jobs block merging.')
          PY
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262
        with:
          persist-credentials: false
          ref: ${{ github.sha }}
          fetch-depth: 0
      - name: Download test and security evidence
        uses: actions/download-artifact@d3f86a106a0bac45b974a628896c90dbdf5c8093
        with:
          name: feature-quality-evidence
          path: ${{ runner.temp }}/quality-reports
      - name: Verify reports and TDD/break-test evidence
        uses: xpossystems/ci-policy-public@__ACTION_SHA__
        env:
          GITHUB_TOKEN: ${{ github.token }}
        with:
          mode: verify
          root: ${{ github.workspace }}
          reports: ${{ runner.temp }}/quality-reports
"""

WORKFLOW = REQUIRED_HEADER + ENVIRONMENT + PLAN_RUN_JOBS + SCAN_VERIFY_JOBS
BASELINE_WORKFLOW = BASELINE_HEADER + ENVIRONMENT + PLAN_RUN_JOBS.replace('mode: run', 'mode: baseline')

REPOSITORY_WORKFLOW = """# Repository baseline caller: .github/workflows/feature-tests.yml
# Public distribution; only centrally approved profiles can pass.
# Baseline execution records tests only; the separate required workflow gates merging.
name: Feature tests

"on":
  pull_request:
  workflow_dispatch:

permissions:
  contents: read

jobs:
  tests:
    uses: xpossystems/ci-policy-public/.github/workflows/category-tests.yml@__POLICY_SHA__
"""


def _verified_sha(value, label):
    if not isinstance(value, str) or re.fullmatch(r"[0-9a-fA-F]{40}", value) is None:
        raise ValueError(label + " must be a verified immutable 40-hex commit SHA")
    sha = value.lower()
    if len(set(sha)) == 1 or sha in {"deadbeef" * 5, "0123456789" * 4, "1234567890" * 4}:
        raise ValueError(label + " must be a verified commit, not a placeholder")
    return sha


def generate_workflow(*, action_sha: str) -> str:
    """Render deterministic YAML using only a full immutable action commit SHA."""
    return WORKFLOW.replace("__ACTION_SHA__", _verified_sha(action_sha, "action SHA"))


def generate_baseline_workflow(action_sha: str) -> str:
    """Render central category-tests.yml without circular TDD verification."""
    return BASELINE_WORKFLOW.replace("__ACTION_SHA__", _verified_sha(action_sha, "action SHA"))


def generate_repository_workflow(policy_sha: str) -> str:
    """Render a public feature-tests.yml caller pinned to policy history."""
    return REPOSITORY_WORKFLOW.replace("__POLICY_SHA__", _verified_sha(policy_sha, "policy SHA"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Render draft workflow YAML to stdout without applying changes.",
        epilog="Verify the referenced commit first. Public baseline distribution; merge-group evidence requires separate per-PR association support.",
        allow_abbrev=False,
    )
    parser.add_argument("--kind", choices=("required", "baseline", "repository"), default="required")
    pins = parser.add_mutually_exclusive_group(required=True)
    pins.add_argument("--action-sha", help="Verified action commit in xpossystems/ci-policy-public for required or baseline workflows")
    pins.add_argument("--policy-sha", help="Verified policy commit containing category-tests.yml for a repository caller")
    args = parser.parse_args(argv)
    try:
        if args.kind == "repository":
            if args.policy_sha is None:
                parser.error("--kind repository requires --policy-sha")
            rendered = generate_repository_workflow(args.policy_sha)
        else:
            if args.action_sha is None:
                parser.error("required and baseline workflows require --action-sha")
            rendered = (generate_baseline_workflow(args.action_sha) if args.kind == "baseline"
                        else generate_workflow(action_sha=args.action_sha))
    except ValueError as error:
        parser.error(str(error))
    print(rendered, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
